<!-- wp:paragraph -->
<p>白鷺総合行政書士事務所（以下「当事務所」といいます）は、業務上お預かりする個人情報の重要性を認識し、個人情報の保護に関する法律その他の関係法令および行政書士法に定める守秘義務を遵守し、以下のとおり取り扱います。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第1条（個人情報の定義）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>本ポリシーにおいて個人情報とは、生存する個人に関する情報であって、氏名、生年月日、住所、電話番号、メールアドレスその他の記述等により特定の個人を識別できるもの、および個人識別符号が含まれるものをいいます。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第2条（個人情報の取得）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>当事務所は、適法かつ公正な手段によって個人情報を取得します。ご依頼、お問い合わせ、面談、書類の受領などを通じて取得することがあります。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第3条（利用目的）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>当事務所は、取得した個人情報を次の目的の範囲内で利用します。</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>ご依頼いただいた業務の遂行および官公署への申請・届出のため</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>お問い合わせやご相談への回答のため</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>ご依頼にかかる報酬および実費のご請求のため</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>業務に関するご連絡およびご案内のため</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>法令にもとづく記録の作成および保存のため</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>上記の目的の範囲を超えて利用する場合は、あらかじめご本人の同意をいただきます。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第4条（第三者への提供）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>当事務所は、次のいずれかに該当する場合を除き、ご本人の同意なく個人情報を第三者に提供しません。</p>
<!-- /wp:paragraph -->

<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>法令にもとづく場合</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>人の生命、身体または財産の保護のために必要であって、ご本人の同意を得ることが困難な場合</li>
<!-- /wp:list-item --><!-- wp:list-item -->
<li>国の機関等の法令に定める事務の遂行に協力する必要がある場合</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->

<!-- wp:paragraph -->
<p>ご依頼の遂行のために提携先の専門家（司法書士、税理士等）へ提供する場合は、あらかじめその旨をご説明し、同意をいただいたうえで行います。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第5条（安全管理措置）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>当事務所は、個人情報の漏えい、滅失またはき損を防止するため、書類の施錠保管、電子データのアクセス制限およびパスワード管理などの措置を講じます。また、取り扱いを委託する場合には、委託先に対して必要かつ適切な監督を行います。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第6条（開示・訂正・利用停止）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>ご本人から、個人情報の開示、訂正、追加、削除または利用停止のお申し出があった場合は、ご本人であることを確認したうえで、法令に従い速やかに対応します。お申し出は第8条の窓口までご連絡ください。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第7条（守秘義務）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>行政書士および行政書士であった者は、正当な理由がなく、業務上取り扱った事項について知り得た秘密を漏らしてはならないと定められています。当事務所は、業務の終了後においても同様に秘密を保持します。</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第8条（お問い合わせ窓口）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>本ポリシーおよび個人情報の取り扱いに関するお問い合わせは、下記までご連絡ください。</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
