<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">第9条（本ポリシーの変更）</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>当事務所は、法令の改正や業務内容の変更に応じて、本ポリシーを変更することがあります。変更後の内容は、本ページに掲載した時点から適用されます。</p>
