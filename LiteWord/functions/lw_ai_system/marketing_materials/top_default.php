### トップページのSEO重要ポイント

**1. タイトルタグの最適化**
- 形式: 「企業名/サービス名 | キーワード | 補足」
- 例: 「〇〇整体院 | 渋谷駅徒歩3分 | 肩こり・腰痛専門」
- 30〜60文字程度

**2. メタディスクリプション**
- 120〜160文字で魅力を伝える
- CTAを含める「今すぐお問い合わせ」など

**3. 見出し構造（H1, H2, H3）**
- H1は1ページに1つ（企業名/サービス名）
- H2でセクションを区切る
- キーワードを自然に含める

**4. 内部リンク設計**
- トップページから重要ページへリンク
- 「ピラーページ」への導線を確保
- アンカーテキストにキーワードを含める

**5. 構造化データ**
- Organization（企業情報）
- LocalBusiness（地域ビジネス）
- BreadcrumbList（パンくずリスト）

### Core Web Vitals 2025基準

| 指標 | 基準値 | 対策 |
|-----|-------|-----|
| LCP | 2.5秒以下 | ヒーロー画像のプリロード、WebP形式、CDN |
| INP | 200ms以下 | JSの最適化、サードパーティスクリプトの遅延読み込み |
| CLS | 0.1以下 | 画像サイズ指定、フォント最適化 |

**表示速度 vs デザインのトレードオフ:**
- アニメーション → 必要最小限に
- 動画背景 → 軽量化 or 代替画像を用意
- 3D要素 → 本当に必要か再検討
- Webフォント → システムフォントも検討

