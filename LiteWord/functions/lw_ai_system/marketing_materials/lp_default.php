## コピーライティングの原則

### キャッチコピー

**効果的なパターン:**
- 数字を入れる（「3分で完了」「満足度98%」）
- ターゲットを明示（「○○な方へ」）
- ベネフィットを端的に（「〜できる」「〜になれる」）
- 問いかけ（「まだ○○で消耗してますか？」）

### ボディコピー

**読みやすさのポイント:**
- 一文は短く（40文字以内目安）
- 専門用語を避ける
- 箇条書きを活用
- 重要部分は太字・色変え

### CTA文言

**効果的なパターン:**
- 動詞で始める（「今すぐ申し込む」）
- ベネフィットを含める（「無料で試してみる」）
- 緊急性を持たせる（「限定○名」「本日まで」）
- ハードルを下げる（「まずは相談」「30秒で完了」）

